/**
 * Extra groupings used by Odd One Out (docs/EXERCISE-CATALOG.md §2.3), from
 * perceptual to abstract. Colour tags are only given when the emoji has one
 * clear colour on every platform.
 */
export type ColourTag = 'red' | 'yellow' | 'green' | 'blue' | 'white' | 'orange';
/** Subcategories inside one CategoryId (see SUB_PARENT). */
export type SubTag = 'farm' | 'sea' | 'wild' | 'insect' | 'vegetable' | 'baked' | 'land' | 'water';
/** Thematic sets: things found together in one place or activity. */
export type ThemeTag = 'beach' | 'sky' | 'writing' | 'bathroom';
/** Abstract properties that cut across categories. */
export type AbstractTag = 'cold' | 'hot' | 'light' | 'flies' | 'sweet';
export type GroupTag = ColourTag | SubTag | ThemeTag | AbstractTag;
/** `atypical`: a poor example of its category (a crown as clothing), kept out of category rounds. */
export type ConceptTag = GroupTag | 'atypical';

export type TagKind = 'colour' | 'sub' | 'theme' | 'abstract';

