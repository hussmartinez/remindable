/**
 * Picture analogies, ordered by difficulty: part–whole, then object–location,
 * then function, then cause–effect.
 */
export type RelationType = 'partOf' | 'livesIn' | 'goesOn' | 'wornOn' | 'usedFor' | 'gives' | 'becomes';

export type Relation = {
  type: RelationType;
  /** Concept id at the other end: "bird → tree". */
  to: string;
  /** One sentence that names the link, shown as feedback. */
  why: Localized;
  /** A tempting wrong choice that is clearly not this relation (bee → flower, not honey). */
  lure?: string;
  /** Answers of the same type that would also be defensible here; never offered. */
  avoid?: string[];
};

export type Concept = {
  id: string;
  emoji: string;
  cat: CategoryId;
  /** 1 = very common word, 3 = less frequent. */
  tier: 1 | 2 | 3;
  word: Localized;
  feature: Localized;
  place: Localized;
  tags?: ConceptTag[];
  /** Groups this concept partly fits (a hen can flap a little, fish is also food); it is never the odd one for them. */
  borderline?: (GroupTag | CategoryId)[];
  relations?: Relation[];
};

